//! Snapshot update orchestration.
//!
//! Network and package authentication live in chromium-crs. This module
//! only coordinates validated bytes, provenance, and generated Rust output.

use std::{fs, path::Path};

use anyhow::{Context, Result, bail, ensure};
use chromium_crs::{COMPONENT_UPDATE_URL, ComponentSnapshot, download_latest};

use crate::generator;

/// Downloads and writes a changed, fully validated snapshot.
pub(crate) fn update(root: &Path) -> Result<()> {
    let snapshot = download_latest()?;
    let source = snapshot.source_metadata()?;
    let generated = generator::generate_component(&source, snapshot.crs())?;
    let payload_path = root.join("chromium-crs/data/crs.pb");
    let checked_in = fs::read(&payload_path).ok();

    // Keep provenance paired with the payload that is actually checked in.
    if payload_is_current(checked_in.as_deref(), snapshot.crs()) {
        println!(
            "Chrome Root Store is unchanged in PKI Metadata component {}",
            snapshot.component_version()
        );
        return Ok(());
    }

    let payload_written = write_if_changed(&payload_path, snapshot.crs())?;
    ensure!(
        payload_written,
        "snapshot change detection disagrees with file update"
    );
    write_source_lock(root, &snapshot, generated.root_store_version)?;
    generator::write_generated_source(root, &generated.source)?;

    println!(
        "updated Chrome Root Store from PKI Metadata component {}, version {} \
         ({} anchors, {} IDs)",
        snapshot.component_version(),
        generated.root_store_version,
        generated.anchor_count,
        generated.id_count
    );
    Ok(())
}
/// Checks the locked payload, metadata, and generated source without network access.
pub(crate) fn check(root: &Path) -> Result<()> {
    let current = generator::generate(root)?;
    generator::ensure_generated_source_current(root, &current.source)?;
    println!(
        "checked locked Chrome Root Store version {} ({} anchors, {} IDs)",
        current.root_store_version, current.anchor_count, current.id_count
    );
    Ok(())
}

/// Checks local consistency and compares against the latest authenticated component.
pub(crate) fn check_latest(root: &Path) -> Result<()> {
    let current = generator::generate(root)?;
    generator::ensure_generated_source_current(root, &current.source)?;

    let snapshot = download_latest()?;
    let source = snapshot.source_metadata()?;
    let candidate = generator::generate_component(&source, snapshot.crs())?;
    let checked_in = fs::read(root.join("chromium-crs/data/crs.pb"))
        .context("failed to read checked-in chromium-crs/data/crs.pb")?;

    ensure!(
        candidate.root_store_version >= current.root_store_version,
        "component Root Store version {} is older than checked-in version {}",
        candidate.root_store_version,
        current.root_store_version
    );
    if checked_in == snapshot.crs() {
        println!(
            "Chrome Root Store is current at PKI Metadata component {}",
            snapshot.component_version()
        );
        return Ok(());
    }

    bail!(
        "Chrome Root Store changed in PKI Metadata component {}; \
         run cargo run -p chromium-crs -- update",
        snapshot.component_version()
    )
}

/// Returns whether the candidate payload exactly matches the checked-in bytes.
fn payload_is_current(checked_in: Option<&[u8]>, candidate: &[u8]) -> bool {
    checked_in == Some(candidate)
}
/// Writes the human-reviewable provenance paired with the payload.
fn write_source_lock(root: &Path, snapshot: &ComponentSnapshot, version: i64) -> Result<bool> {
    let contents = format!(
        "# Generated by cargo run -p chromium-crs -- update; do not edit by hand.\n\
         component_id = {component_id:?}\n\
         component_version = {component_version:?}\n\
         browser_version = {browser_version:?}\n\
         crx_sha256 = {crx_sha256:?}\n\
         crs_sha256 = {crs_sha256:?}\n\
         root_store_version = {version}\n\
         source = {source:?}\n",
        component_id = chromium_crs::PKI_METADATA_COMPONENT_ID,
        component_version = snapshot.component_version(),
        browser_version = snapshot.browser_version(),
        crx_sha256 = hex::encode(snapshot.crx_sha256()),
        crs_sha256 = hex::encode(snapshot.crs_sha256()),
        source = COMPONENT_UPDATE_URL,
    );
    write_if_changed(
        &root.join("chromium-crs/data/SOURCE.toml"),
        contents.as_bytes(),
    )
}

/// Replaces a file only when its complete contents changed.
fn write_if_changed(path: &Path, contents: &[u8]) -> Result<bool> {
    if fs::read(path).ok().as_deref() == Some(contents) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create {}", parent.display()))?;
    }
    fs::write(path, contents).with_context(|| format!("failed to write {}", path.display()))?;
    Ok(true)
}
#[cfg(test)]
mod tests {
    use std::{path::PathBuf, time::SystemTime};

    use super::*;

    struct SnapshotFixture(PathBuf);

    impl Drop for SnapshotFixture {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn local_check_rejects_changed_payload_provenance_and_generated_source() {
        let nonce = SystemTime::now()
            .duration_since(SystemTime::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let fixture = SnapshotFixture(
            std::env::temp_dir().join(format!("chromium-crs-check-{}-{nonce}", std::process::id())),
        );
        let workspace = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        let paths = [
            "chromium-crs/data/crs.pb",
            "chromium-crs/data/SOURCE.toml",
            "chromium-roots/src/generated.rs",
        ];
        for path in paths {
            write_if_changed(
                &fixture.0.join(path),
                &fs::read(workspace.join(path)).unwrap(),
            )
            .unwrap();
        }
        check(&fixture.0).expect("locked snapshot must pass without downloading an update");

        for (path, diagnostic) in paths.into_iter().zip([
            "SHA-256 does not match",
            "pinned component endpoint",
            "generated.rs is stale",
        ]) {
            let destination = fixture.0.join(path);
            let original = fs::read(&destination).unwrap();
            let changed = if path.ends_with("SOURCE.toml") {
                String::from_utf8(original.clone())
                    .unwrap()
                    .replace(COMPONENT_UPDATE_URL, "https://example.com/component")
                    .into_bytes()
            } else {
                let mut bytes = original.clone();
                bytes.push(b'\n');
                bytes
            };
            fs::write(&destination, changed).unwrap();
            let error = check(&fixture.0).expect_err("modified snapshot must be rejected");
            assert!(error.to_string().contains(diagnostic), "{error:#}");
            fs::write(destination, original).unwrap();
        }
    }

    #[test]
    fn payload_change_detection_is_byte_exact() {
        assert!(payload_is_current(Some(&b"same"[..]), b"same"));
        assert!(!payload_is_current(Some(&b"old"[..]), b"new"));
        assert!(!payload_is_current(None, b"new"));
    }
}
