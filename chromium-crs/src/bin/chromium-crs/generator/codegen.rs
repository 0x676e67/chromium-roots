//! Typed Rust source generation for validated Root Store data.
//!
//! Values are emitted through quote tokens rather than assembled Rust strings,
//! then formatted once with prettyplease for deterministic releases.

use anyhow::{Context, Result};
use chromium_crs::{ConstraintSet, SourceMetadata, TrustAnchorKind};
use proc_macro2::{Literal, Span, TokenStream};
use quote::{format_ident, quote};
use syn::LitInt;

use super::ValidatedTrustAnchor;

/// Emits the complete static data module and its provenance constants.
pub(super) fn generate_source(
    source: &SourceMetadata,
    version: i64,
    anchors: &[ValidatedTrustAnchor<'_>],
    trust_anchor_ids: &[&[u8]],
) -> Result<String> {
    let GeneratedAnchorTokens {
        certificate_items,
        certificate_names,
        anchor_items,
    } = generate_anchor_tokens(anchors);
    let component_id = Literal::string(source.component_id());
    let component_version = Literal::string(source.component_version());
    let browser_version = Literal::string(source.browser_version());
    let package_hash = Literal::byte_string(source.crx_sha256());
    let payload_hash = Literal::byte_string(source.crs_sha256());

    let trust_anchor_ids = trust_anchor_ids
        .iter()
        .map(|id| Literal::byte_string(id))
        .collect::<Vec<_>>();
    let tokens = quote! {
        #(#certificate_items)*

        #[doc = " Chrome PKI Metadata component ID used for this snapshot."]
        pub const SOURCE_COMPONENT_ID: &str = #component_id;

        #[doc = " Chrome PKI Metadata component version used for this snapshot."]
        pub const SOURCE_COMPONENT_VERSION: &str = #component_version;

        #[doc = " Chrome Stable version used to request the component."]
        pub const SOURCE_BROWSER_VERSION: &str = #browser_version;

        #[doc = " SHA-256 of the verified CRX3 package."]
        pub const SOURCE_CRX_SHA256: [u8; 32] = *#package_hash;

        #[doc = " SHA-256 of the serialized root-store payload."]
        pub const SOURCE_CRS_SHA256: [u8; 32] = *#payload_hash;

        #[doc = " Chrome Root Store major version used by this snapshot."]
        pub const ROOT_STORE_VERSION: i64 = #version;


        // Trust Anchor IDs are independent Chromium metadata, not certificate
        // fingerprints. This is their single generated representation.
        const TRUST_ANCHOR_IDS: &[&[u8]] = &[#(#trust_anchor_ids),*];


        #[doc = " Classical X.509 certificates trusted for TLS by this Root Store snapshot."]
        #[doc = " "]
        #[doc = " Entries retain Chromium source order. Additional certificates are included"]
        #[doc = " only when Chromium marks them as TLS trust anchors."]
        pub const TLS_SERVER_ROOT_CERTS: &[rustls_pki_types::CertificateDer<'static>] = &[
            #(rustls_pki_types::CertificateDer::from_slice(#certificate_names)),*
        ];

        #[doc = " Chromium TLS trust anchors and their source metadata."]
        pub static TLS_TRUST_ANCHORS: &[TrustAnchor] = &[
            #(#anchor_items),*
        ];


        #[doc = " Length-prefixed Trust Anchor IDs for native"]
        #[doc = " requested-trust-anchor setter APIs."]
        #[doc = " "]
        #[doc = " IDs use deterministic Chromium source order. The TLS requested list is"]
        #[doc = " semantically unordered, so this byte order is not a Chrome fingerprint."]
        pub const ENCODED_TRUST_ANCHOR_IDS: &[u8] =
            &encode_trust_anchor_ids::<
                { encoded_trust_anchor_ids_len(TRUST_ANCHOR_IDS) }
            >(TRUST_ANCHOR_IDS);
    };
    let syntax = syn::parse2(tokens).context("generated Root Store source is invalid Rust")?;
    let mut source =
        String::from("// @generated by cargo run -p chromium-crs -- generate; do not edit.\n");
    source.push_str(&prettyplease::unparse(&syntax));
    Ok(source)
}

/// Generated token groups that share certificate identifiers.
struct GeneratedAnchorTokens {
    /// Private certificate byte constants.
    certificate_items: Vec<TokenStream>,
    /// Certificate identifiers reused by the public DER list.
    certificate_names: Vec<proc_macro2::Ident>,
    /// Complete Chrome trust-anchor metadata entries.
    anchor_items: Vec<TokenStream>,
}

/// Converts validated anchors into reusable source token groups.
fn generate_anchor_tokens(anchors: &[ValidatedTrustAnchor<'_>]) -> GeneratedAnchorTokens {
    let mut certificate_items = Vec::with_capacity(anchors.len());
    let mut certificate_names = Vec::with_capacity(anchors.len());
    let mut anchor_items = Vec::with_capacity(anchors.len());

    for (index, validated) in anchors.iter().enumerate() {
        let anchor = validated.metadata;
        let certificate_name = format_ident!("CERTIFICATE_{index}");
        let certificate = Literal::byte_string(&anchor.der);
        let hash = Literal::byte_string(&validated.sha256);
        let kind = match anchor.kind {
            TrustAnchorKind::Root => quote!(TrustAnchorKind::Root),
            TrustAnchorKind::Additional => quote!(TrustAnchorKind::Additional),
        };
        let crs_root_id = optional_number(anchor.crs_root_id);
        let trust_anchor_id = validated.trust_anchor_id_index.map_or_else(
            || quote!(None),
            |index| quote!(Some(TRUST_ANCHOR_IDS[#index])),
        );
        let constraints = anchor
            .constraints
            .iter()
            .map(constraint_tokens)
            .collect::<Vec<_>>();
        let ev_policy_oids = anchor
            .ev_policy_oids
            .iter()
            .map(|oid| Literal::string(oid))
            .collect::<Vec<_>>();
        let display_name = optional_string(anchor.display_name.as_deref());
        let eutl = anchor.eutl;
        let enforce_anchor_expiry = anchor.enforce_anchor_expiry;
        let enforce_anchor_constraints = anchor.enforce_anchor_constraints;

        certificate_items.push(quote! {
            const #certificate_name: &[u8] = #certificate;
        });
        certificate_names.push(certificate_name.clone());
        anchor_items.push(quote! {
            TrustAnchor {
                der: #certificate_name,
                sha256: *#hash,
                kind: #kind,
                crs_root_id: #crs_root_id,
                trust_anchor_id: #trust_anchor_id,
                constraints: &[#(#constraints),*],
                ev_policy_oids: &[#(#ev_policy_oids),*],
                display_name: #display_name,
                eutl: #eutl,
                enforce_anchor_expiry: #enforce_anchor_expiry,
                enforce_anchor_constraints: #enforce_anchor_constraints,
            }
        });
    }

    GeneratedAnchorTokens {
        certificate_items,
        certificate_names,
        anchor_items,
    }
}

/// Converts one validated constraint set into typed source tokens.
fn constraint_tokens(constraint: &ConstraintSet) -> TokenStream {
    let sct_not_after_sec = optional_number(constraint.sct_not_after_sec);
    let sct_all_after_sec = optional_number(constraint.sct_all_after_sec);
    let min_version = optional_string(constraint.min_version.as_deref());
    let max_version_exclusive = optional_string(constraint.max_version_exclusive.as_deref());
    let permitted_dns_names = constraint
        .permitted_dns_names
        .iter()
        .map(|name| Literal::string(name))
        .collect::<Vec<_>>();
    let index_not_after = optional_number(constraint.index_not_after);
    let index_after = optional_number(constraint.index_after);
    let validity_starts_not_after_sec = optional_number(constraint.validity_starts_not_after_sec);
    let validity_starts_after_sec = optional_number(constraint.validity_starts_after_sec);

    quote! {
        RootConstraint {
            sct_not_after_sec: #sct_not_after_sec,
            sct_all_after_sec: #sct_all_after_sec,
            min_version: #min_version,
            max_version_exclusive: #max_version_exclusive,
            permitted_dns_names: &[#(#permitted_dns_names),*],
            index_not_after: #index_not_after,
            index_after: #index_after,
            validity_starts_not_after_sec: #validity_starts_not_after_sec,
            validity_starts_after_sec: #validity_starts_after_sec,
        }
    }
}

/// Converts an optional integer into a suffixed Rust literal.
fn optional_number<T: ReadableInteger>(value: Option<T>) -> TokenStream {
    value.map_or_else(
        || quote!(None),
        |value| {
            let value = value.readable_tokens();
            quote!(Some(#value))
        },
    )
}

/// Produces a readable, explicitly typed integer token.
trait ReadableInteger {
    /// Converts the value into source tokens.
    fn readable_tokens(self) -> TokenStream;
}

/// Implements readable literals for signed metadata integer types.
macro_rules! impl_readable_signed {
    ($integer:ty, $suffix:literal) => {
        impl ReadableInteger for $integer {
            fn readable_tokens(self) -> TokenStream {
                let value = i128::from(self);
                let literal = integer_literal(value.unsigned_abs(), $suffix);
                if value.is_negative() {
                    quote!(-#literal)
                } else {
                    quote!(#literal)
                }
            }
        }
    };
}

impl_readable_signed!(i32, "i32");
impl_readable_signed!(i64, "i64");

impl ReadableInteger for u64 {
    fn readable_tokens(self) -> TokenStream {
        let literal = integer_literal(u128::from(self), "u64");
        quote!(#literal)
    }
}

/// Groups decimal digits while retaining an explicit type suffix.
fn integer_literal(value: u128, suffix: &str) -> LitInt {
    let digits = value.to_string();
    let first_separator = digits.len() % 3;
    let mut next_separator = if first_separator == 0 {
        3
    } else {
        first_separator
    };
    let mut literal = String::with_capacity(digits.len() + digits.len() / 3 + suffix.len() + 1);

    for (index, digit) in digits.chars().enumerate() {
        if index == next_separator {
            literal.push('_');
            next_separator += 3;
        }
        literal.push(digit);
    }
    literal.push('_');
    literal.push_str(suffix);
    LitInt::new(&literal, Span::call_site())
}

/// Quotes an optional string as source tokens.
fn optional_string(value: Option<&str>) -> TokenStream {
    value.map_or_else(
        || quote!(None),
        |value| {
            let value = Literal::string(value);
            quote!(Some(#value))
        },
    )
}
